// Wins, losses and draws of public games, keyed by the hash of a random device token.
// The raw token is hashed as soon as it reaches the server and is never stored or logged.

import { createHash } from 'node:crypto';
import { attachDatabasePool } from '@vercel/functions';
import pg from 'pg';

export const TOP = 10;

// Browsers send crypto.randomUUID(); accept similar random strings, nothing else
const TOKEN = /^[A-Za-z0-9-]{32,64}$/;

export function hashToken(token) {
  if (typeof token !== 'string' || !TOKEN.test(token)) return null;
  return createHash('sha256').update(token).digest('hex');
}

const toEntry = (rank, p) => ({
  rank,
  name: p.name,
  wins: p.wins,
  losses: p.losses,
  draws: p.draws,
  games: p.wins + p.losses + p.draws,
});

const OUTCOME_COLUMNS = { WIN: [1, 0, 0], LOSS: [0, 1, 0], DRAW: [0, 0, 1] };

// Same table and columns as the Java version created, so existing results keep working
const CREATE_TABLE = `
  CREATE TABLE IF NOT EXISTS player_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    display_name VARCHAR(32) NOT NULL,
    wins INTEGER NOT NULL DEFAULT 0,
    losses INTEGER NOT NULL DEFAULT 0,
    draws INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
  )`;

const SELECT_PROFILE = `SELECT display_name AS name, wins, losses, draws, updated_at FROM player_profile`;

/** @param db anything with query(text, params) returning { rows }: a pg Pool, or PGlite in tests */
export function createSqlLeaderboard(db, clock = () => new Date()) {
  let ready = null;
  const prepare = () => (ready ??= db.query(CREATE_TABLE).catch(error => {
    ready = null;
    throw error;
  }));

  return {
    async record(tokenHash, name, outcome) {
      if (!tokenHash) return;
      await prepare();
      const [wins, losses, draws] = OUTCOME_COLUMNS[outcome];
      await db.query(
        `INSERT INTO player_profile (token_hash, display_name, wins, losses, draws, created_at, updated_at)
         VALUES ($1, $2, $3, $4, $5, $6, $6)
         ON CONFLICT (token_hash) DO UPDATE SET
           display_name = EXCLUDED.display_name,
           wins = player_profile.wins + EXCLUDED.wins,
           losses = player_profile.losses + EXCLUDED.losses,
           draws = player_profile.draws + EXCLUDED.draws,
           updated_at = EXCLUDED.updated_at`,
        [tokenHash, name, wins, losses, draws, clock()],
      );
    },

    /** The top players, plus the asking player's own line (null if they haven't played a public game) */
    async board(token) {
      await prepare();
      const ranking = await db.query(
        `${SELECT_PROFILE} WHERE wins > 0 ORDER BY wins DESC, losses ASC, updated_at ASC LIMIT ${TOP}`,
      );
      const top = ranking.rows.map((p, i) => toEntry(i + 1, p));

      const hash = hashToken(token);
      if (!hash) return { top, you: null };
      const own = await db.query(`${SELECT_PROFILE} WHERE token_hash = $1`, [hash]);
      if (own.rows.length === 0) return { top, you: null };
      const me = own.rows[0];
      const above = await db.query(
        `SELECT count(*) AS above FROM player_profile
         WHERE wins > $1 OR (wins = $1 AND losses < $2) OR (wins = $1 AND losses = $2 AND updated_at < $3)`,
        [me.wins, me.losses, me.updated_at],
      );
      return { top, you: toEntry(Number(above.rows[0].above) + 1, me) };
    },
  };
}

/** Without DATABASE_URL (local development): results are kept in memory and reset on restart */
export function createMemoryLeaderboard(clock = () => new Date()) {
  const profiles = new Map();
  const before = (a, b) => b.wins - a.wins || a.losses - b.losses || a.updatedAt - b.updatedAt;

  return {
    async record(tokenHash, name, outcome) {
      if (!tokenHash) return;
      const profile = profiles.get(tokenHash) ?? { wins: 0, losses: 0, draws: 0 };
      const [wins, losses, draws] = OUTCOME_COLUMNS[outcome];
      profiles.set(tokenHash, {
        name,
        wins: profile.wins + wins,
        losses: profile.losses + losses,
        draws: profile.draws + draws,
        updatedAt: clock().getTime(),
      });
    },
    async board(token) {
      const all = [...profiles.values()];
      const top = all.filter(p => p.wins > 0).sort(before).slice(0, TOP).map((p, i) => toEntry(i + 1, p));
      const hash = hashToken(token);
      const me = hash && profiles.get(hash);
      if (!me) return { top, you: null };
      return { top, you: toEntry(all.filter(p => before(p, me) < 0).length + 1, me) };
    },
  };
}

let shared = null;

export function sharedLeaderboard(env = process.env) {
  if (!shared) {
    if (env.DATABASE_URL) {
      const pool = new pg.Pool({ connectionString: env.DATABASE_URL.trim(), max: 2, idleTimeoutMillis: 5000 });
      pool.on('error', error => console.error('Database error:', error.message));
      attachDatabasePool(pool);
      shared = createSqlLeaderboard(pool);
    } else {
      shared = createMemoryLeaderboard();
    }
  }
  return shared;
}
