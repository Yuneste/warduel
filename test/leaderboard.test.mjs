// The leaderboard rules, run against real Postgres SQL (PGlite) and against the in-memory version
// used without a database. The legacy test checks a table created exactly as the Java version did.

import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { describe, it } from 'node:test';
import { PGlite } from '@electric-sql/pglite';
import { createMemoryLeaderboard, createSqlLeaderboard, hashToken, TOP } from '../lib/leaderboard.js';

function ticking() {
  let now = Date.parse('2026-01-01T00:00:00Z');
  const clock = () => new Date(now);
  clock.tick = () => {
    now += 1000;
  };
  return clock;
}

const token = () => randomUUID();

const variants = {
  'Postgres SQL': clock => createSqlLeaderboard(new PGlite(), clock),
  'in memory': clock => createMemoryLeaderboard(clock),
};

for (const [name, create] of Object.entries(variants)) {
  describe(`leaderboard (${name})`, () => {
    const setup = () => {
      const clock = ticking();
      const board = create(clock);
      const record = (t, playerName, outcome) => board.record(hashToken(t), playerName, outcome);
      const win = async (t, playerName, times) => {
        for (let i = 0; i < times; i++) {
          await record(t, playerName, 'WIN');
          clock.tick();
        }
      };
      return { board, record, win };
    };

    it('records results per device token and keeps the latest name', async () => {
      const { board, record } = setup();
      const t = token();
      await record(t, 'Yuko', 'WIN');
      await record(t, 'Yuko', 'LOSS');
      await record(t, 'Yuko K.', 'WIN');
      await record(t, 'Yuko K.', 'DRAW');

      const { you } = await board.board(t);
      assert.equal(you.name, 'Yuko K.');
      assert.deepEqual([you.wins, you.losses, you.draws, you.games], [2, 1, 1, 4]);
    });

    it('ranks by wins, then fewer losses, then who got there first', async () => {
      const { board, record, win } = setup();
      const [ada, bob, cy, dee] = [token(), token(), token(), token()];
      await win(ada, 'Ada', 3);
      await win(bob, 'Bob', 5);
      await win(cy, 'Cy', 3);
      await record(cy, 'Cy', 'LOSS');
      await win(dee, 'Dee', 3); // same as Ada but later
      await record(token(), 'Nobody', 'LOSS'); // no wins: not on the board

      const result = await board.board(dee);
      assert.deepEqual(result.top.map(e => e.name), ['Bob', 'Ada', 'Dee', 'Cy']);
      assert.deepEqual(result.top.map(e => e.rank), [1, 2, 3, 4]);
      assert.equal(result.you.rank, 3);
    });

    it('shows only the top ten', async () => {
      const { board, win } = setup();
      for (let i = 0; i < 12; i++) await win(token(), `P${i}`, 1);
      assert.equal((await board.board(null)).top.length, TOP);
    });

    it('ignores missing or malformed tokens', async () => {
      const { board, record } = setup();
      await record(null, 'Anon', 'WIN');
      await record('short', 'Anon', 'WIN');
      await record(`${'x'.repeat(40)}<script>`, 'Anon', 'WIN');

      assert.deepEqual((await board.board(null)).top, []);
      assert.equal((await board.board('not-a-token')).you, null);
    });
  });
}

describe('leaderboard data', () => {
  it('stores only a hash of the token', async () => {
    const db = new PGlite();
    const t = token();
    await createSqlLeaderboard(db).record(hashToken(t), 'Kai', 'WIN');

    const { rows } = await db.query('SELECT token_hash FROM player_profile');
    assert.equal(rows[0].token_hash.length, 64);
    assert.ok(!rows[0].token_hash.includes(t));
  });

  it('keeps working with the table the Java version created', async () => {
    const db = new PGlite();
    await db.exec(`
      CREATE TABLE player_profile (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
        display_name VARCHAR(32) NOT NULL,
        draws INTEGER NOT NULL,
        losses INTEGER NOT NULL,
        token_hash VARCHAR(64) NOT NULL UNIQUE,
        updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
        wins INTEGER NOT NULL
      );
      CREATE INDEX idx_profile_wins ON player_profile (wins);
    `);
    const veteran = token();
    await db.query(
      `INSERT INTO player_profile (created_at, display_name, draws, losses, token_hash, updated_at, wins)
       VALUES (now(), 'Veteran', 1, 2, $1, now(), 7)`,
      [hashToken(veteran)],
    );

    const board = createSqlLeaderboard(db);
    await board.record(hashToken(veteran), 'Veteran', 'WIN');

    const { you } = await board.board(veteran);
    assert.deepEqual([you.name, you.wins, you.losses, you.draws, you.rank], ['Veteran', 8, 2, 1, 1]);
  });
});
